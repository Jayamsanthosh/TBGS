CREATE PROCEDURE [VMaster].[SHOW_MAN_POWER_APPROVED_SETTINGS]
(
    @STATUS VARCHAR(20)
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        A.MAN_POWER_APPROVED_ID,
        A.COMPANY_ID,
        C.COMPANY_NAME,
        A.DEPARTMENT_ID,
        D.DEPARTMENT_NAME,
        A.DESIGNATION_ID,
        DS.DESIGNATION_NAME,
        A.EMPLOYMENT_TYPE_ID,
        EMP.EMPLOYMENT_TYPE_NAME,
        A.NEW_APPROVED_MAN_POWER,
        A.MAN_POWER_REQUEST_ID,
        A.APPROVED_BY,
        A.REMARKS,
        A.STATUS_MASTER,

        A.CREATED_BY,
        A.CREATED_DATE,
        A.MODIFIED_BY,
        A.MODIFIED_DATE

    FROM VMaster.TBL_MAN_POWER_APPROVED_SETTINGS A

    INNER JOIN VMaster.TBL_COMPANY_MASTER C
        ON A.COMPANY_ID = C.COMPANY_ID

    INNER JOIN VMaster.TBL_DEPARTMENT_MASTER D
        ON A.DEPARTMENT_ID = D.DEPARTMENT_ID

    INNER JOIN VMaster.TBL_DESIGNATION_MASTER DS
        ON A.DESIGNATION_ID = DS.DESIGNATION_ID

    INNER JOIN VMaster.TBL_EMPLOYMENT_TYPE_MASTER EMP
        ON A.EMPLOYMENT_TYPE_ID = EMP.EMPLOYMENT_TYPE_ID

    WHERE A.STATUS_MASTER = @STATUS

    ORDER BY
        C.COMPANY_NAME,
        D.DEPARTMENT_NAME,
        DS.DESIGNATION_NAME,
        EMP.EMPLOYMENT_TYPE_NAME;
END
GO

