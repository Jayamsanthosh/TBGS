CREATE PROCEDURE [VMaster].[GET_TRIP_TEMPLATE_MASTER]
(
    @TRIP_TEMPLATE_ID INT
)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        A.TRIP_TEMPLATE_ID,
        A.TRIP_TEMPLATE_NAME,
        A.TRIP_TEMPLATE_DESCRIPTION,

        A.FROM_LOCATION_ID,
        FL.LOCATION_NAME AS FROM_LOCATION,

        A.TO_LOCATION_ID,
        TL.LOCATION_NAME AS TO_LOCATION,

        A.DISTANCE_KM,
        A.REMARKS,
        A.STATUS_MASTER

    FROM VMaster.TBL_TRIP_TEMPLATE_MASTER A

    LEFT JOIN VMaster.TBL_LOCATION_MASTER FL
        ON A.FROM_LOCATION_ID = FL.LOCATION_ID

    LEFT JOIN VMaster.TBL_LOCATION_MASTER TL
        ON A.TO_LOCATION_ID = TL.LOCATION_ID

    WHERE A.TRIP_TEMPLATE_ID = @TRIP_TEMPLATE_ID;
END
GO
