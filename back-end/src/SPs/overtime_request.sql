)
AS
BEGIN
    SET NOCOUNT ON;

    IF   EXISTS
    (
        SELECT 1
        FROM [VREQUEST].[TBL_OVERTIME_REQUEST]
        WHERE OT_REQUEST_REF_NO = @OT_REQUEST_REF_NO
		AND STATUS_MASTER ='CL'
     
    )
    BEGIN
        SELECT
            'error' AS STATUS,
            'Already Submitted Can''t do anychanges Contact To Admin' AS MESSAGE,
            '' AS DATA;

    END
	 else begin

    UPDATE [VREQUEST].[TBL_OVERTIME_REQUEST]
    SET
        OT_REQUEST_REF_NO = @OT_REQUEST_REF_NO,
        MONTH_ENTERED = @MONTH_ENTERED,
        YEAR_ENTERED = @YEAR_ENTERED,
        EMP_ID = @EMP_ID,
        FIRST_NAME = @FIRST_NAME,
        MIDDLE_NAME = @MIDDLE_NAME,
        LAST_NAME = @LAST_NAME,
        COMPANY_ID = @COMPANY_ID,
        DEPARTMENT_ID = @DEPARTMENT_ID,
        DESIGNATION_ID = @DESIGNATION_ID,
        DEPARTMENT_GROUP_ID = @DEPARTMENT_GROUP_ID,
        DESIGNATION_GROUP_ID = @DESIGNATION_GROUP_ID,
        CAMP_ID = @CAMP_ID,
        STORE_ID = @STORE_ID,
        EMPLOYMENT_TYPE_ID = @EMPLOYMENT_TYPE_ID,
        CURRENCY_ID = @CURRENCY_ID,
        OT_FROM_DATE = @OT_FROM_DATE,
        OT_TO_DATE = @OT_TO_DATE,
        OT_HOURS = @OT_HOURS,
        REQUEST_AMOUNT = @REQUEST_AMOUNT,
        APPROVED_AMOUNT = @APPROVED_AMOUNT,
        PAYMENT_REF_NO = @PAYMENT_REF_NO,
        PAYMENT_MODE_ID = @PAYMENT_MODE_ID,
        BANK_ID = @BANK_ID,
        ACCOUNT_NO = @ACCOUNT_NO,
        PAID_STATUS = @PAID_STATUS,
        REASON = @REASON,
        REMARKS = @REMARKS,
        STATUS_MASTER = @STATUS_MASTER,
        MODIFIED_BY = @USER,
        MODIFIED_DATE = GETDATE(),
        MODIFIED_MAC_ADDRESS = @MAC_ADDRESS
    WHERE OT_REQUEST_REF_NO = @OT_REQUEST_REF_NO
	
    SELECT
        '' AS STATUS,
        'Overtime Request Updated Successfully' AS MESSAGE,
        @OT_REQUEST_REF_NO AS DATA;
END
