CREATE   PROCEDURE [VREQUEST].[DELETE_OVERTIME_REQUEST]
(
    @OT_REQUEST_REF_NO varchar(50),
    @USER VARCHAR(50),
    @ROLE VARCHAR(50),
    @MAC_ADDRESS VARCHAR(50)
)
AS
BEGIN
    SET NOCOUNT ON;

    IF @ROLE <> 'Admin'
    BEGIN
        SELECT
            'error' AS STATUS,
            'No Rights To Delete' AS MESSAGE,
            '' AS DATA
    END

   else IF NOT EXISTS
    (
        SELECT 1
        FROM [VREQUEST].[TBL_OVERTIME_REQUEST]
        WHERE OT_REQUEST_REF_NO = @OT_REQUEST_REF_NO
    )
    BEGIN
        SELECT
            'error' AS STATUS,
            'Overtime Request Not Found' AS MESSAGE,
            '' AS DATA;
    
    END
 
	else  begin
    DELETE FROM [VREQUEST].[TBL_OVERTIME_REQUEST]
    WHERE OT_REQUEST_REF_NO = @OT_REQUEST_REF_NO

    SELECT
        '' AS STATUS,  'Overtime Request Deleted Successfully' AS MESSAGE,@OT_REQUEST_REF_NO AS DATA
END
 end
