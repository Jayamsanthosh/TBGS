-- Get purchase quotation hdr: additional-cost columns removed.
ALTER PROCEDURE [VPurchase].[GET_PURCHASE_QUOTATION_HDR]
(
    @PURCHASE_QUOTATION_NO VARCHAR(50) = NULL,
    @SNO INT = NULL,
    @Status VARCHAR(20) = 'ALL',
    @FromDate DATE = NULL,
    @ToDate DATE = NULL,
    @CompanyId INT = NULL,
    @SupplierBpId INT = NULL,
    @Search NVARCHAR(200) = NULL,
    @Page INT = NULL,
    @PageSize INT = NULL
)
AS
BEGIN
    SET NOCOUNT ON;

    IF @PURCHASE_QUOTATION_NO IS NOT NULL
    BEGIN
        SELECT * FROM [VPurchase].[TBL_PURCHASE_QUOTATION_HDR]
        WHERE PURCHASE_QUOTATION_NO = @PURCHASE_QUOTATION_NO;
        RETURN;
    END

    IF @SNO IS NOT NULL
    BEGIN
        SELECT * FROM [VPurchase].[TBL_PURCHASE_QUOTATION_HDR]
        WHERE SNO = @SNO;
        RETURN;
    END

    DROP TABLE IF EXISTS #REPORT_PQ_HDR;
    ;WITH CTE AS
    (
        SELECT
             A.SNO AS sno
            ,A.PURCHASE_QUOTATION_NO AS purchaseQuotationNo
            ,A.PURCHASE_QUOTATION_NO AS refNo
            ,COALESCE(
                NULLIF(LTRIM(RTRIM(A.PURCHASE_REQUEST_NO)), ''),
                (SELECT MIN(LTRIM(RTRIM(D.PURCHASE_REQUEST_NO)))
                   FROM [VPurchase].[TBL_PURCHASE_QUOTATION_DTL] D
                  WHERE D.PURCHASE_QUOTATION_NO = A.PURCHASE_QUOTATION_NO
                    AND NULLIF(LTRIM(RTRIM(D.PURCHASE_REQUEST_NO)), '') IS NOT NULL)
             ) AS purchaseRequestNo
            ,A.PURCHASE_QUOTATION_DATE AS purchaseQuotationDate
            ,A.COMPANY_ID AS companyId
            ,C.COMPANY_NAME AS companyName
            ,A.SUPPLIER_BP_ID AS supplierBpId
            ,BP.BP_NAME AS supplierName
            ,A.BRANCH_ID AS branchId
            ,BR.BRANCH_NAME AS branchName
            ,A.PO_STORE_ID AS poStoreId
            ,PS.STORE_NAME AS poStoreName
            ,A.SUPPLIER_QUOTATION_NO AS supplierQuotationNo
            ,A.SUPPLIER_QUOTATION_DATE AS supplierQuotationDate
            ,A.VALID_FROM_DATE AS validFromDate
            ,A.VALID_TO_DATE AS validToDate
            ,A.PAYMENT_TERM_ID AS paymentTermId
            ,A.PAYMENT_MODE_ID AS paymentModeId
            ,A.SHIPMENT_MODE_ID AS shipmentModeId
            ,SM.SHIPMENT_MODE_NAME AS shipmentModeName
            ,A.DELIVERY_DATE AS deliveryDate
            ,A.DELIVERY_TERM AS deliveryTerm
            ,A.SHIPMENT_REMARKS AS shipmentRemarks
            ,A.DELIVERY_LOCATION_ID AS deliveryLocationId
            ,A.TOTAL_SUB_TOTAL_HDR_AMOUNT_FC AS totalSubTotalHdrAmountFc
            ,A.TOTAL_DISCOUNT_HDR_AMOUNT_FC AS totalDiscountHdrAmountFc

            ,A.TOTAL_PRODUCT_HDR_AMOUNT_FC AS totalProductHdrAmountFc
            ,A.TOTAL_VAT_HDR_AMOUNT_FC AS totalVatHdrAmountFc
            ,A.FINAL_PRODUCT_HDR_AMOUNT_FC AS finalProductHdrAmountFc
            ,A.CURRENCY_ID AS currencyId
            ,A.EXCHANGE_RATE AS exchangeRate
            ,A.TOTAL_SUB_TOTAL_HDR_AMOUNT_LC AS totalSubTotalHdrAmountLc
            ,A.TOTAL_DISCOUNT_HDR_AMOUNT_LC AS totalDiscountHdrAmountLc

            ,A.TOTAL_PRODUCT_HDR_AMOUNT_LC AS totalProductHdrAmountLc
            ,A.TOTAL_TAX_HDR_AMOUNT_LC AS totalTaxHdrAmountLc
            ,A.FINAL_PRODUCT_HDR_AMOUNT_LC AS finalProductHdrAmountLc
            ,A.SECTION_HEAD_RESPONSE_PERSON_EMP_ID AS sectionHeadPersonEmpId
            ,A.SECTION_HEAD_RESPONSE_DATE AS sectionHeadDate
            ,CASE UPPER(LTRIM(RTRIM(ISNULL(A.SECTION_HEAD_RESPONSE_STATUS, ''))))
                WHEN 'APPROVAL' THEN 'APPROVED'
                WHEN 'APPROVED' THEN 'APPROVED'
                WHEN 'REJECT'   THEN 'REJECTED'
                WHEN 'REJECTED' THEN 'REJECTED'
                WHEN 'HOLD'     THEN 'HOLD'
                ELSE '' END AS sectionHeadStatus
            ,A.SECTION_HEAD_RESPONSE_REMARKS AS sectionHeadRemarks
            ,A.SECTION_HEAD_RESPONSE_IP_ADDRESS AS sectionHeadIpAddress
            ,A.RESPONSE_1_EMP_ID AS response1EmpId
            ,A.RESPONSE_1_DATE AS response1Date
            ,CASE UPPER(LTRIM(RTRIM(ISNULL(A.RESPONSE_1_STATUS, ''))))
                WHEN 'APPROVAL' THEN 'APPROVED'
                WHEN 'APPROVED' THEN 'APPROVED'
                WHEN 'REJECT'   THEN 'REJECTED'
                WHEN 'REJECTED' THEN 'REJECTED'
                WHEN 'HOLD'     THEN 'HOLD'
                ELSE '' END AS response1Status
            ,A.RESPONSE_1_REMARKS AS response1Remarks
            ,A.RESPONSE_1_IP_ADDRESS AS response1IpAddress
            ,A.RESPONSE_2_EMP_ID AS response2EmpId
            ,A.RESPONSE_2_DATE AS response2Date
            ,CASE UPPER(LTRIM(RTRIM(ISNULL(A.RESPONSE_2_STATUS, ''))))
                WHEN 'APPROVAL' THEN 'APPROVED'
                WHEN 'APPROVED' THEN 'APPROVED'
                WHEN 'REJECT'   THEN 'REJECTED'
                WHEN 'REJECTED' THEN 'REJECTED'
                WHEN 'HOLD'     THEN 'HOLD'
                ELSE '' END AS response2Status
            ,A.RESPONSE_2_REMARKS AS response2Remarks
            ,A.RESPONSE_2_IP_ADDRESS AS response2IpAddress
            ,A.FINAL_RESPONSE_EMP_ID AS finalResponseEmpId
            ,A.FINAL_RESPONSE_DATE AS finalResponseDate
            ,A.FINAL_RESPONSE_REMARKS AS finalResponseRemarks
            ,A.FINAL_RESPONSE_IP_ADDRESS AS finalResponseIpAddress
            -- Non-cascading terminal rollup, same rule as Purchase Request:
            -- APPROVED only when the FINAL level is approved, REJECTED if any
            -- level rejected, HOLD if any level held, otherwise PENDING.
            ,CASE
                WHEN UPPER(LTRIM(RTRIM(ISNULL(A.FINAL_RESPONSE_STATUS,'')))) IN ('APPROVAL','APPROVED')
                    THEN 'APPROVED'
                WHEN UPPER(LTRIM(RTRIM(ISNULL(A.FINAL_RESPONSE_STATUS,'')))) IN ('REJECT','REJECTED')
                    OR  UPPER(LTRIM(RTRIM(ISNULL(A.RESPONSE_2_STATUS,'')))) IN ('REJECT','REJECTED')
                    OR  UPPER(LTRIM(RTRIM(ISNULL(A.RESPONSE_1_STATUS,'')))) IN ('REJECT','REJECTED')
                    OR  UPPER(LTRIM(RTRIM(ISNULL(A.SECTION_HEAD_RESPONSE_STATUS,'')))) IN ('REJECT','REJECTED')
                    THEN 'REJECTED'
                WHEN UPPER(LTRIM(RTRIM(ISNULL(A.FINAL_RESPONSE_STATUS,'')))) = 'HOLD'
                    OR  UPPER(LTRIM(RTRIM(ISNULL(A.RESPONSE_2_STATUS,'')))) = 'HOLD'
                    OR  UPPER(LTRIM(RTRIM(ISNULL(A.RESPONSE_1_STATUS,'')))) = 'HOLD'
                    OR  UPPER(LTRIM(RTRIM(ISNULL(A.SECTION_HEAD_RESPONSE_STATUS,'')))) = 'HOLD'
                    THEN 'HOLD'
                ELSE 'PENDING' END AS finalResponseStatus
            ,A.QUOTATION_STATUS_ID AS quotationStatusId
            ,ST.STATUS_NAME AS quotationStatusName
            ,A.REMARKS AS remarks
            ,A.STATUS_ENTRY AS statusEntry
            ,A.CREATED_BY AS createdBy
            ,A.CREATED_DATE AS createdDate
        FROM [VPurchase].[TBL_PURCHASE_QUOTATION_HDR] A
        LEFT JOIN VMaster.TBL_COMPANY_MASTER C  ON C.COMPANY_ID = A.COMPANY_ID
        LEFT JOIN VMaster.TBL_BUSINESS_PARTNER_MASTER BP ON BP.BP_ID = A.SUPPLIER_BP_ID
        LEFT JOIN VMaster.TBL_BRANCH_MASTER BR ON BR.BRANCH_ID = A.BRANCH_ID
        LEFT JOIN VMaster.TBL_STORE_MASTER PS ON PS.STORE_ID = A.PO_STORE_ID
        LEFT JOIN VMaster.TBL_SHIPMENT_MODE_MASTER SM ON SM.SHIPMENT_MODE_ID = A.SHIPMENT_MODE_ID
        LEFT JOIN VMaster.TBL_STATUS_MASTER ST ON ST.STATUS_ID = A.QUOTATION_STATUS_ID
        WHERE (@FromDate IS NULL OR CONVERT(DATE, A.PURCHASE_QUOTATION_DATE) >= @FromDate)
          AND (@ToDate   IS NULL OR CONVERT(DATE, A.PURCHASE_QUOTATION_DATE) <= @ToDate)
          AND (@CompanyId IS NULL OR A.COMPANY_ID = @CompanyId)
          AND (@SupplierBpId IS NULL OR A.SUPPLIER_BP_ID = @SupplierBpId)
    )
    SELECT * INTO #REPORT_PQ_HDR
    FROM CTE
    WHERE (@Status = 'ALL' OR finalResponseStatus = UPPER(LTRIM(RTRIM(@Status))))
      AND (@Search IS NULL OR CONCAT(
          ISNULL(CAST(sno AS VARCHAR(20)), ''), ' ',
          ISNULL(refNo, ''), ' ',
          ISNULL(purchaseRequestNo, ''), ' ',
          ISNULL(supplierName, ''), ' ',
          ISNULL(supplierQuotationNo, ''), ' ',
          ISNULL(companyName, ''), ' ',
          ISNULL(branchName, ''), ' ',
          ISNULL(poStoreName, ''), ' ',
          ISNULL(shipmentModeName, '')
      ) LIKE '%' + @Search + '%');

    IF @Page IS NOT NULL AND @PageSize IS NOT NULL
    BEGIN
        SELECT COUNT(*) AS Total FROM #REPORT_PQ_HDR;
        SELECT * FROM #REPORT_PQ_HDR
        ORDER BY sno DESC
        OFFSET (@Page - 1) * @PageSize ROWS
        FETCH NEXT @PageSize ROWS ONLY;
    END
    ELSE
    BEGIN
        SELECT * FROM #REPORT_PQ_HDR ORDER BY sno DESC;
    END
    DROP TABLE IF EXISTS #REPORT_PQ_HDR;
END
GO
