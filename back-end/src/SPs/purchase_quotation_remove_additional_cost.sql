        @CAMP_ID, @REQUEST_STORE_ID, @REFERENCE_TYPE_ID, @REFERENCE_NO, @LINE_NO,
        @MAIN_CATEGORY_ID, @SUB_CATEGORY_ID, @PRODUCT_ID,
        @NO_OF_PCS_PER_PACKING, @TOTAL_QUANTITY, @UOM_ID, @TOTAL_PACKING, @ALT_UOM_ID,
        @RATE, @SUB_TOTAL_AMOUNT_FC, @DISCOUNT_PERCENTAGE, @DISCOUNT_AMOUNT_FC,
        @TOTAL_PRODUCT_AMOUNT_FC, @TAX_ID, @TAX_PERCENTAGE, @TAX_AMOUNT_FC, @FINAL_AMOUNT_FC,
        @EXCHANGE_RATE, @SUB_TOTAL_AMOUNT_LC, @DISCOUNT_AMOUNT_LC,
        @TOTAL_PRODUCT_AMOUNT_LC, @TAX_AMOUNT_LC, @FINAL_AMOUNT_LC,
