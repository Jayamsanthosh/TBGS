        TOTAL_VAT_HDR_AMOUNT_FC         = @TOTAL_VAT_HDR_AMOUNT_FC,
        FINAL_PRODUCT_HDR_AMOUNT_FC     = @FINAL_PRODUCT_HDR_AMOUNT_FC,
        CURRENCY_ID    = @CURRENCY_ID,
