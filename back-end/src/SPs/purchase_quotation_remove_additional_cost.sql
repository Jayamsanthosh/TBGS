        TOTAL_TAX_HDR_AMOUNT_LC         = @TOTAL_TAX_HDR_AMOUNT_LC,
        FINAL_PRODUCT_HDR_AMOUNT_LC     = @FINAL_PRODUCT_HDR_AMOUNT_LC,
