ALTER PROCEDURE [VPurchase].[TBL_UPDATE_PURCHASE_INVOICE_HDR_VALUES]
(
    @PURCHASE_INVOICE_REF_NO VARCHAR(50)
)
AS
BEGIN
    SET NOCOUNT ON

    DECLARE
         @TOTAL_SUB_TOTAL_FC        DECIMAL(15,3) = 0
        ,@TOTAL_DISCOUNT_FC         DECIMAL(15,3) = 0
        ,@TOTAL_ADDITIONAL_COST_FC  DECIMAL(15,3) = 0
        ,@TOTAL_PRODUCT_FC          DECIMAL(15,3) = 0
        ,@TOTAL_TAX_FC              DECIMAL(15,3) = 0
        ,@FINAL_PRODUCT_FC          DECIMAL(15,3) = 0
        ,@TOTAL_SUB_TOTAL_LC        DECIMAL(15,3) = 0
        ,@TOTAL_DISCOUNT_LC         DECIMAL(15,3) = 0
        ,@TOTAL_ADDITIONAL_COST_LC  DECIMAL(15,3) = 0
        ,@TOTAL_PRODUCT_LC          DECIMAL(15,3) = 0
        ,@TOTAL_TAX_LC              DECIMAL(15,3) = 0
        ,@FINAL_PRODUCT_LC          DECIMAL(15,3) = 0
        ,@ADDITIONAL_TAX_FC         DECIMAL(15,3) = 0
        ,@ADDITIONAL_TAX_LC         DECIMAL(15,3) = 0

    UPDATE [VPurchase].[TBL_PURCHASE_INVOICE_DTL]
    SET
         TAX_AMOUNT_FC = ROUND(ISNULL(TOTAL_PRODUCT_AMOUNT_FC, 0) * ISNULL(TAX_PERCENTAGE, 0) / 100, 3)
        ,TAX_AMOUNT_LC = ROUND(ISNULL(TOTAL_PRODUCT_AMOUNT_LC, 0) * ISNULL(TAX_PERCENTAGE, 0) / 100, 3)
    WHERE PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO

    UPDATE [VPurchase].[TBL_PURCHASE_INVOICE_DTL]
    SET
         FINAL_AMOUNT_FC = ROUND(ISNULL(TOTAL_PRODUCT_AMOUNT_FC, 0) + ISNULL(TAX_AMOUNT_FC, 0), 3)
        ,FINAL_AMOUNT_LC = ROUND(ISNULL(TOTAL_PRODUCT_AMOUNT_LC, 0) + ISNULL(TAX_AMOUNT_LC, 0), 3)
    WHERE PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO

    SELECT
         @TOTAL_SUB_TOTAL_FC = ISNULL(SUM(ISNULL(SUB_TOTAL_AMOUNT_FC, 0)), 0)
        ,@TOTAL_DISCOUNT_FC = ISNULL(SUM(ISNULL(DISCOUNT_AMOUNT_FC, 0)), 0)
        ,@TOTAL_PRODUCT_FC = ISNULL(SUM(ISNULL(TOTAL_PRODUCT_AMOUNT_FC, 0)), 0)
        ,@TOTAL_TAX_FC = ISNULL(SUM(ISNULL(TAX_AMOUNT_FC, 0)), 0)
        ,@FINAL_PRODUCT_FC = ISNULL(SUM(ISNULL(FINAL_AMOUNT_FC, 0)), 0)
        ,@TOTAL_SUB_TOTAL_LC = ISNULL(SUM(ISNULL(SUB_TOTAL_AMOUNT_LC, 0)), 0)
        ,@TOTAL_DISCOUNT_LC = ISNULL(SUM(ISNULL(DISCOUNT_AMOUNT_LC, 0)), 0)
        ,@TOTAL_PRODUCT_LC = ISNULL(SUM(ISNULL(TOTAL_PRODUCT_AMOUNT_LC, 0)), 0)
        ,@TOTAL_TAX_LC = ISNULL(SUM(ISNULL(TAX_AMOUNT_LC, 0)), 0)
        ,@FINAL_PRODUCT_LC = ISNULL(SUM(ISNULL(FINAL_AMOUNT_LC, 0)), 0)
    FROM [VPurchase].[TBL_PURCHASE_INVOICE_DTL]
    WHERE PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO

    SELECT
         @TOTAL_ADDITIONAL_COST_FC = ISNULL(SUM(ISNULL(AMOUNT_FC, 0)), 0)
        ,@TOTAL_ADDITIONAL_COST_LC = ISNULL(SUM(ISNULL(AMOUNT_LC, 0)), 0)
        ,@ADDITIONAL_TAX_FC = ISNULL(SUM(ISNULL(TAX_AMOUNT_FC, 0)), 0)
        ,@ADDITIONAL_TAX_LC = ISNULL(SUM(ISNULL(TAX_AMOUNT_LC, 0)), 0)
    FROM [VPurchase].[TBL_PURCHASE_INVOICE_ADDITIONAL_CHARGES_DTL]
    WHERE PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO

    SET @TOTAL_TAX_FC = @TOTAL_TAX_FC + @ADDITIONAL_TAX_FC
    SET @TOTAL_TAX_LC = @TOTAL_TAX_LC + @ADDITIONAL_TAX_LC
    SET @FINAL_PRODUCT_FC = @TOTAL_PRODUCT_FC + @TOTAL_TAX_FC + @TOTAL_ADDITIONAL_COST_FC
    SET @FINAL_PRODUCT_LC = @TOTAL_PRODUCT_LC + @TOTAL_TAX_LC + @TOTAL_ADDITIONAL_COST_LC

    UPDATE [VPurchase].[TBL_PURCHASE_INVOICE_HDR]
    SET
         TOTAL_SUB_TOTAL_HDR_AMOUNT_FC = ROUND(@TOTAL_SUB_TOTAL_FC, 3)
        ,TOTAL_DISCOUNT_HDR_AMOUNT_FC = ROUND(@TOTAL_DISCOUNT_FC, 3)
        ,TOTAL_ADDITIONAL_COST_AMOUNT_FC = ROUND(@TOTAL_ADDITIONAL_COST_FC, 3)
        ,TOTAL_PRODUCT_HDR_AMOUNT_FC = ROUND(@TOTAL_PRODUCT_FC, 3)
        ,TOTAL_TAX_HDR_AMOUNT_FC = ROUND(@TOTAL_TAX_FC, 3)
        ,FINAL_PRODUCT_HDR_AMOUNT_FC = ROUND(@FINAL_PRODUCT_FC, 3)
        ,TOTAL_SUB_TOTAL_HDR_AMOUNT_LC = ROUND(@TOTAL_SUB_TOTAL_LC, 3)
        ,TOTAL_DISCOUNT_HDR_AMOUNT_LC = ROUND(@TOTAL_DISCOUNT_LC, 3)
        ,TOTAL_ADDITIONAL_COST_AMOUNT_LC = ROUND(@TOTAL_ADDITIONAL_COST_LC, 3)
        ,TOTAL_PRODUCT_HDR_AMOUNT_LC = ROUND(@TOTAL_PRODUCT_LC, 3)
        ,TOTAL_TAX_HDR_AMOUNT_LC = ROUND(@TOTAL_TAX_LC, 3)
        ,FINAL_PRODUCT_HDR_AMOUNT_LC = ROUND(@FINAL_PRODUCT_LC, 3)
    WHERE PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO
END
GO
