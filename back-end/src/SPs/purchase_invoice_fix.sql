ALTER PROCEDURE [VPurchase].[SHOW_PURCHASE_INVOICE_HDR]
(
    @PURCHASE_INVOICE_REF_NO VARCHAR(50) = NULL
)
AS
BEGIN
    SET NOCOUNT ON

    SELECT
         H.SNO AS ID
        ,H.DRAFT_REF_NO
        ,H.PURCHASE_INVOICE_REF_NO
        ,CONVERT(VARCHAR(10), H.PURCHASE_INVOICE_DATE, 23) AS PURCHASE_INVOICE_DATE
        ,H.PURCHASE_ORDER_NO
        ,H.SUPPLIER_INVOICE_NO
        ,CONVERT(VARCHAR(10), H.SUPPLIER_INVOICE_DATE, 23) AS SUPPLIER_INVOICE_DATE
        ,H.COMPANY_ID
        ,ISNULL(C.COMPANY_NAME, CAST(H.COMPANY_ID AS VARCHAR(50))) AS COMPANY_NAME
        ,H.BRANCH_ID
        ,ISNULL(BR.BRANCH_NAME, CAST(H.BRANCH_ID AS VARCHAR(50))) AS BRANCH_NAME
        ,H.CAMP_ID
        ,ISNULL(CM.CAMP_NAME, CAST(H.CAMP_ID AS VARCHAR(50))) AS CAMP_NAME
        ,H.STORE_ID
        ,ISNULL(ST.STORE_NAME, CAST(H.STORE_ID AS VARCHAR(50))) AS STORE_NAME
        ,H.SUPPLIER_BP_ID
        ,ISNULL(BP.BP_NAME, CAST(H.SUPPLIER_BP_ID AS VARCHAR(50))) AS SUPPLIER_BP_NAME
        ,H.CURRENCY_ID
        ,ISNULL(CU.CURRENCY_NAME, CAST(H.CURRENCY_ID AS VARCHAR(50))) AS CURRENCY_NAME
        ,H.EXCHANGE_RATE
        ,H.PAYMENT_TERM_ID
        ,ISNULL(PT.PAYMENT_TERM_NAME, CAST(H.PAYMENT_TERM_ID AS VARCHAR(50))) AS PAYMENT_TERM_NAME
        ,H.PAYMENT_MODE_ID
        ,ISNULL(PM.PAYMENT_MODE_NAME, CAST(H.PAYMENT_MODE_ID AS VARCHAR(50))) AS PAYMENT_MODE_NAME
        ,CONVERT(VARCHAR(10), H.DUE_DATE, 23) AS DUE_DATE
        ,H.TOTAL_SUB_TOTAL_HDR_AMOUNT_FC
        ,H.TOTAL_DISCOUNT_HDR_AMOUNT_FC
        ,H.TOTAL_ADDITIONAL_COST_AMOUNT_FC
        ,H.TOTAL_PRODUCT_HDR_AMOUNT_FC
        ,H.TOTAL_TAX_HDR_AMOUNT_FC
        ,H.FINAL_PRODUCT_HDR_AMOUNT_FC
        ,H.TOTAL_SUB_TOTAL_HDR_AMOUNT_LC
        ,H.TOTAL_DISCOUNT_HDR_AMOUNT_LC
        ,H.TOTAL_ADDITIONAL_COST_AMOUNT_LC
        ,H.TOTAL_PRODUCT_HDR_AMOUNT_LC
        ,H.TOTAL_TAX_HDR_AMOUNT_LC
        ,H.FINAL_PRODUCT_HDR_AMOUNT_LC
        ,H.STATUS_ID
        ,ISNULL(STM.STATUS_NAME, CAST(H.STATUS_ID AS VARCHAR(50))) AS STATUS_NAME
        ,H.RESPONSE_BY_EMP_ID
        ,H.RESPONSE_DATE
        ,H.RESPONSE_REMARKS
        ,H.REMARKS
        ,H.LINK_PAGES_ID
        ,H.STATUS_ENTRY
        ,CASE WHEN EXISTS (
            SELECT 1 FROM [VMaster].[TBL_DOCUMENT_MANAGEMENT_SYSTEM] DMS
            WHERE DMS.PAGE_REF_NO = H.PURCHASE_INVOICE_REF_NO
        ) THEN CAST(1 AS BIT) ELSE CAST(0 AS BIT) END AS HAS_DOCUMENT
    FROM [VPurchase].[TBL_PURCHASE_INVOICE_HDR] H
    LEFT JOIN [VMASTER].[TBL_COMPANY_MASTER]          C  ON C.COMPANY_ID       = H.COMPANY_ID
    LEFT JOIN [VMASTER].[TBL_BRANCH_Master]           BR ON BR.BRANCH_ID       = H.BRANCH_ID
    LEFT JOIN [VMASTER].[TBL_CAMP_MASTER]             CM ON CM.CAMP_ID         = H.CAMP_ID
    LEFT JOIN [VMASTER].[TBL_STORE_MASTER]            ST ON ST.STORE_ID        = H.STORE_ID
    LEFT JOIN [VMASTER].[TBL_BUSINESS_PARTNER_MASTER] BP ON BP.BP_ID            = H.SUPPLIER_BP_ID
    LEFT JOIN [VMASTER].[TBL_CURRENCY_MASTER]         CU ON CU.CURRENCY_ID      = H.CURRENCY_ID
    LEFT JOIN [VMASTER].[TBL_PAYMENT_TERM_MASTER]     PT ON PT.PAYMENT_TERM_ID  = H.PAYMENT_TERM_ID
    LEFT JOIN [VMASTER].[TBL_PAYMENT_MODE_MASTER]     PM ON PM.PAYMENT_MODE_ID  = H.PAYMENT_MODE_ID
    LEFT JOIN [VMASTER].[TBL_STATUS_MASTER]           STM ON STM.STATUS_ID      = H.STATUS_ID
    WHERE (@PURCHASE_INVOICE_REF_NO IS NULL OR H.PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO)
    ORDER BY H.PURCHASE_INVOICE_REF_NO DESC
END
