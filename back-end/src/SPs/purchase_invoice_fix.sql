    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('VPurchase.TBL_PURCHASE_INVOICE_HDR')
      AND name = 'IX_TBL_PUR_INV_HDR_LIST'
)
BEGIN
    CREATE INDEX [IX_TBL_PUR_INV_HDR_LIST]
        ON [VPurchase].[TBL_PURCHASE_INVOICE_HDR] ([COMPANY_ID], [PURCHASE_INVOICE_DATE], [SUPPLIER_BP_ID]);
