/* DTL line-level exchange rate (HDR already has one). */
IF COL_LENGTH('VPurchase.TBL_PURCHASE_INVOICE_DTL', 'EXCHANGE_RATE') IS NULL
BEGIN
    ALTER TABLE [VPurchase].[TBL_PURCHASE_INVOICE_DTL]
        ADD [EXCHANGE_RATE] DECIMAL(15,6) NULL;
END
GO

/* A draft reference may be blank; only real values must be unique. */
IF EXISTS (
    SELECT 1 FROM sys.objects
    WHERE parent_object_id = OBJECT_ID('VPurchase.TBL_PURCHASE_INVOICE_HDR')
      AND name = 'uk_draft_ref_no_po_inv_hdr'
)
BEGIN
    ALTER TABLE [VPurchase].[TBL_PURCHASE_INVOICE_HDR]
        DROP CONSTRAINT [uk_draft_ref_no_po_inv_hdr];
END
GO

IF NOT EXISTS (
    SELECT 1 FROM sys.indexes
    WHERE object_id = OBJECT_ID('VPurchase.TBL_PURCHASE_INVOICE_HDR')
      AND name = 'UX_TBL_PUR_INV_HDR_DRAFT'
)
BEGIN
    CREATE UNIQUE INDEX [UX_TBL_PUR_INV_HDR_DRAFT]
        ON [VPurchase].[TBL_PURCHASE_INVOICE_HDR] ([DRAFT_REF_NO])
        WHERE [DRAFT_REF_NO] IS NOT NULL;
END
GO

