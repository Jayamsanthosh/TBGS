ALTER PROCEDURE [VPurchase].[DELETE_PURCHASE_INVOICE_HDR]
(
    @PURCHASE_INVOICE_REF_NO VARCHAR(50)
)
AS
BEGIN
    SET NOCOUNT ON
    SET XACT_ABORT ON

    IF ISNULL(LTRIM(RTRIM(@PURCHASE_INVOICE_REF_NO)), '') = ''
    BEGIN
        SELECT 'error' AS STATUS, 'PURCHASE_INVOICE_REF_NO is required.' AS MESSAGE, '' AS DATA
        RETURN
    END

    IF NOT EXISTS (
        SELECT 1 FROM [VPurchase].[TBL_PURCHASE_INVOICE_HDR]
        WHERE PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO
    )
    BEGIN
        SELECT 'error' AS STATUS, 'Record Not Found.' AS MESSAGE, '' AS DATA
        RETURN
    END

    IF EXISTS (
        SELECT 1 FROM [VPurchase].[TBL_PURCHASE_INVOICE_HDR]
        WHERE PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO
          AND UPPER(ISNULL(STATUS_ENTRY, '')) IN ('CL', 'SUBMITTED')
    )
    BEGIN
        SELECT 'error' AS STATUS, 'A submitted Purchase Invoice cannot be deleted.' AS MESSAGE, '' AS DATA
        RETURN
    END

    IF EXISTS (
        SELECT 1 FROM [VPurchase].[TBL_PURCHASE_INVOICE_DTL]
        WHERE PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO
    ) OR EXISTS (
        SELECT 1 FROM [VPurchase].[TBL_PURCHASE_INVOICE_ADDITIONAL_CHARGES_DTL]
        WHERE PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO
    )
    BEGIN
        SELECT 'error' AS STATUS, 'Delete the invoice lines and additional charges first.' AS MESSAGE, '' AS DATA
        RETURN
    END

    BEGIN TRY
        BEGIN TRANSACTION

        DELETE FROM [VPurchase].[TBL_PURCHASE_INVOICE_HDR]
        WHERE PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO

        COMMIT TRANSACTION

        SELECT 'success' AS STATUS, 'Record Deleted Successfully.' AS MESSAGE, @PURCHASE_INVOICE_REF_NO AS DATA
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION
        SELECT 'error' AS STATUS, ERROR_MESSAGE() AS MESSAGE, '' AS DATA
    END CATCH
END
GO

