        SELECT 'error' AS STATUS, 'Charge type and amount are required.' AS MESSAGE, '' AS DATA
        RETURN
    END

    BEGIN TRY
        BEGIN TRANSACTION

        UPDATE [VPurchase].[TBL_PURCHASE_INVOICE_ADDITIONAL_CHARGES_DTL]
        SET
             PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO
            ,LINE_NO = @LINE_NO
            ,ADDITIONAL_CHARGE_TYPE_ID = @ADDITIONAL_CHARGE_TYPE_ID
            ,DESCRIPTION = @DESCRIPTION
            ,QUANTITY = @QUANTITY
            ,UOM_ID = @UOM_ID
            ,RATE_FC = @RATE_FC
            ,AMOUNT_FC = @AMOUNT_FC
            ,TAX_ID = @TAX_ID
            ,TAX_PERCENTAGE = @TAX_PERCENTAGE
            ,TAX_AMOUNT_FC = @TAX_AMOUNT_FC
            ,FINAL_AMOUNT_FC = @FINAL_AMOUNT_FC
            ,AMOUNT_LC = @AMOUNT_LC
            ,TAX_AMOUNT_LC = @TAX_AMOUNT_LC
            ,FINAL_AMOUNT_LC = @FINAL_AMOUNT_LC
            ,REMARKS = @REMARKS
            ,MODIFIED_BY = @USER
            ,MODIFIED_DATE = GETDATE()
            ,MODIFIED_MAC_ADDRESS = @MAC_ADDRESS
        WHERE PURCHASE_INVOICE_ADDITIONAL_CHARGES_DTL_ID = @PURCHASE_INVOICE_ADDITIONAL_CHARGES_DTL_ID

        EXEC [VPurchase].[TBL_UPDATE_PURCHASE_INVOICE_HDR_VALUES] @PURCHASE_INVOICE_REF_NO

        COMMIT TRANSACTION

        SELECT 'success' AS STATUS, 'Record Updated Successfully.' AS MESSAGE, @PURCHASE_INVOICE_ADDITIONAL_CHARGES_DTL_ID AS DATA
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION
        SELECT 'error' AS STATUS, ERROR_MESSAGE() AS MESSAGE, '' AS DATA
    END CATCH
END
