ALTER PROCEDURE [VPurchase].[SHOW_PURCHASE_INVOICE_ADDITIONAL_CHARGES_DTL]
(
    @PURCHASE_INVOICE_REF_NO VARCHAR(50)
)
AS
BEGIN
    SET NOCOUNT ON

    SELECT
         D.PURCHASE_INVOICE_ADDITIONAL_CHARGES_DTL_ID
        ,D.PURCHASE_INVOICE_REF_NO
        ,D.LINE_NO
        ,D.ADDITIONAL_CHARGE_TYPE_ID
        ,ISNULL(A.ADDITIONAL_CHARGE_TYPE_NAME, CAST(D.ADDITIONAL_CHARGE_TYPE_ID AS VARCHAR(50))) AS ADDITIONAL_CHARGE_TYPE_NAME
        ,D.DESCRIPTION
        ,D.QUANTITY
        ,D.UOM_ID
        ,ISNULL(U.UOM_NAME, CAST(D.UOM_ID AS VARCHAR(50))) AS UOM_NAME
        ,D.RATE_FC
        ,D.AMOUNT_FC
        ,D.TAX_ID
        ,ISNULL(T.TAX_NAME, CAST(D.TAX_ID AS VARCHAR(50))) AS TAX_NAME
        ,D.TAX_PERCENTAGE
        ,D.TAX_AMOUNT_FC
        ,D.FINAL_AMOUNT_FC
        ,D.AMOUNT_LC
        ,D.TAX_AMOUNT_LC
        ,D.FINAL_AMOUNT_LC
        ,D.REMARKS
        ,D.STATUS_ENTRY
    FROM [VPurchase].[TBL_PURCHASE_INVOICE_ADDITIONAL_CHARGES_DTL] D
    LEFT JOIN [VMASTER].[TBL_ADDITIONAL_CHARGE_TYPE_MASTER] A ON A.ADDITIONAL_CHARGE_TYPE_ID = D.ADDITIONAL_CHARGE_TYPE_ID
    LEFT JOIN [VMASTER].[TBL_UOM_MASTER]                     U ON U.UOM_ID                     = D.UOM_ID
    LEFT JOIN [VMASTER].[TBL_TAX_MASTER]                     T ON T.TAX_ID                     = D.TAX_ID
    WHERE D.PURCHASE_INVOICE_REF_NO = @PURCHASE_INVOICE_REF_NO
    ORDER BY D.LINE_NO ASC, D.PURCHASE_INVOICE_ADDITIONAL_CHARGES_DTL_ID DESC
END
